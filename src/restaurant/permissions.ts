export function hasRestaurantPermission(
  roleId: RestaurantRoleId,
  moduleId: RestaurantModuleId,
  action: PermissionAction = 'view'
): boolean {
  const role = RESTAURANT_ROLES[roleId];
  if (!role) return false;
  const actions = role.modules[moduleId];
  if (!actions) return false;
  if (action === 'administer') return actions.includes('administer');
  return actions.includes(action) || actions.includes('administer');
}

export function getPermittedRestaurantModules(roleId: RestaurantRoleId) {
  return RESTAURANT_MODULES.filter((m) => hasRestaurantPermission(roleId, m.id, 'view'));
}
