export function hasPlayLandPermission(
  roleId: PlayLandRoleId,
  moduleId: PlayLandModuleId,
  action: PermissionAction = 'view'
): boolean {
  const role = PLAYLAND_ROLES[roleId];
  if (!role) return false;
  const actions = role.modules[moduleId];
  if (!actions) return false;
  if (action === 'administer') return actions.includes('administer');
  return actions.includes(action) || actions.includes('administer');
}

export function getPermittedPlayLandModules(roleId: PlayLandRoleId) {
  return PLAYLAND_MODULES.filter((m) => hasPlayLandPermission(roleId, m.id, 'view'));
}
